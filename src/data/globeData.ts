// Helper to convert GII (0 to 1) into smooth Blue -> Coral/Red color
export function getGIIColor(gii: number): string {
  // Normalize roughly between 0.01 and 0.70
  // Lowest inequality (near 0) = Deep/Vibrant Blue (#2563EB or #0284C7)
  // Moderate inequality (0.25 - 0.40) = Soft Indigo / Peach (#94A3B8 / #FDBA74)
  // High inequality (0.45 - 0.75+) = Coral / Deep Red (#EF4444 or #DC2626)
  const clamped = Math.max(0, Math.min(1, gii / 0.75));

  // Interpolate between Blue [37, 99, 235] and Red [220, 38, 38]
  const r = Math.round(37 + clamped * (220 - 37));
  const g = Math.round(99 + clamped * (38 - 99));
  const b = Math.round(235 + clamped * (38 - 235));

  return `rgb(${r}, ${g}, ${b})`;
}
